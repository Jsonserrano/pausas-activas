PA.idioma = 'es';

/** Texto traducido; si recibe dos textos, elige según el idioma (atajo). */
PA.t = function (clave, en) {
  if (en !== undefined) return PA.idioma === 'en' ? en : clave;
  return (PA.TEXTOS[PA.idioma] && PA.TEXTOS[PA.idioma][clave]) || PA.TEXTOS.es[clave] || clave;
};

PA.traducirPagina = function () {
  document.documentElement.lang = PA.idioma;
  document.querySelectorAll('[data-translate]').forEach(el => {
    const texto = PA.TEXTOS[PA.idioma][el.getAttribute('data-translate')];
    if (!texto) return;
    if (el.hasAttribute('placeholder')) el.setAttribute('placeholder', texto);
    else el.textContent = texto;
  });
  document.querySelectorAll('[data-translate-title]').forEach(el => {
    const texto = PA.TEXTOS[PA.idioma][el.getAttribute('data-translate-title')];
    if (texto) el.setAttribute('title', texto);
  });
};
